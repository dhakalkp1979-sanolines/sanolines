const categories = [
  "Government & Official Services",
  "Immigration & Visa",
  "Jobs & Employment",
  "Money & Banking",
  "Taxes",
  "Healthcare",
  "Education",
  "Transport & Driving",
  "Emergency Services",
  "Travel",
  "Housing",
  "Useful Contacts",
];

const makeCountry = (country, sources) => {
  const services = {};

  categories.forEach((category, index) => {
    const source = sources[index];

    services[category] = {
      description: `${category} information and official services for ${country}.`,
      links: [
        {
          name: source.name,
          url: source.url,
          official: true,
        },
      ],
    };
  });

  services["Calculators & Tools"] = {
    description:
      `Useful Sanolines calculators and tools for ${country}.`,
    links: [
      {
        name: "Sanolines Calculators & Tools",
        url: "./",
        official: false,
      },
    ],
  };

  return services;
};

