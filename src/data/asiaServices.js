const makeLink = (name, url, official = true) => ({
  name,
  url,
  official,
});

const makeCountry = (country, sources) => {
  const services = {};

  categories.forEach((category, index) => {
    const source = sources[index] || sources[0];

    services[category] = {
      description:
        `${category} information and useful resources for ${country}. ` +
        `Sanolines is an information directory and does not provide these services.`,
      links: [
        makeLink(
          source.name,
          source.url,
          source.official !== false
        ),
      ],
    };
  });

  services["Calculators & Tools"] = {
    description:
      `Useful Sanolines calculators and tools for ${country}.`,
    links: [
      {
        name: "Sanolines Calculators & Tools",
        url: "./",
        official: false,
      },
    ],
  };

  return services;
};

